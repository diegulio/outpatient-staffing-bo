import numpy as np
from warnings import catch_warnings, simplefilter
from scipy.stats import norm
from sklearn.gaussian_process import GaussianProcessRegressor
from sklearn.gaussian_process.kernels import WhiteKernel, Matern

from .base_optimizer import BaseOptimizer


class BayesianOptimizer(BaseOptimizer):
    """Bayesian optimization with a GP surrogate and Expected Improvement.

    The GP is fitted in a reduced 30-dimensional space (Admissions and Checkups
    hours per specialty) rather than on the 1,760 detailed scheduling variables.
    At each iteration, EI is maximized over a fresh pool of feasible schedules
    generated by the Gurobi scheduler, and only the highest-EI unevaluated
    candidate is simulated.
    """

    def __init__(self, problem, objective_func):
        super().__init__(problem, objective_func)
        self.name = "Bayesian Optimization"

        # Matern-5/2 + white-noise kernel (see the kernel-sensitivity analysis in
        # kernel_analysis.py and the kernel-sensitivity results of the manuscript).
        kernel = Matern(nu=2.5) + WhiteKernel(noise_level=0.1)

        self.model = GaussianProcessRegressor(
            kernel=kernel,
            normalize_y=True,
            n_restarts_optimizer=10,
            alpha=1e-2  # regularization for numerical stability
        )

    def _reduce_X(self, X):
        """Projects 1,760-dimensional schedules to 30 specialty-activity totals.

        Physician and room identities are dropped because the queue evaluator
        only depends on these totals. Totals are scaled by the 180-hour monthly
        contract cap.
        """
        X_reduced = []
        for x_flat in X:
            x_mat = np.array(x_flat).reshape(self.problem.i, self.problem.j, self.problem.k)
            reduced = []
            for s in range(self.problem.s):
                adm_sum = np.sum(x_mat[self.problem.E[s], 0, :])  # Admissions hours of specialty s
                chk_sum = np.sum(x_mat[self.problem.E[s], 1, :])  # Checkups hours of specialty s
                reduced.extend([adm_sum, chk_sum])
            X_reduced.append(reduced)

        return np.array(X_reduced) / 180.0

    def surrogate(self, model, X_red):
        with catch_warnings():
            simplefilter("ignore")
            return model.predict(X_red, return_std=True)

    def acquisition(self, X_red, Xsamples_red, model, e_pct=0.15):
        """Expected Improvement (maximization form) with a dynamic margin.

        The exploration margin is e_pct times the spread of the posterior mean
        over the evaluated points (or e_pct itself if the spread is zero).
        """
        yhat, _ = self.surrogate(model, X_red)
        best = max(yhat)
        mu, std = self.surrogate(model, Xsamples_red)

        spread = np.max(yhat) - np.min(yhat)
        dynamic_e = e_pct * spread if spread > 0 else e_pct

        impr = mu - best - dynamic_e
        Z = (impr) / (std + 1E-9)
        EI = impr * norm.cdf(Z) + std * norm.pdf(Z)
        return EI

    def opt_acquisition(self, X, y, model):
        from core.gurobi_space import sample_feasible_space

        # 1,000 fresh feasible candidates at every iteration
        Xsamples, _ = sample_feasible_space(self.problem, 1000)

        if len(Xsamples) == 0:
            return None

        # Score candidates in the reduced (30-dimensional) space
        X_red = self._reduce_X(X)
        Xsamples_red = self._reduce_X(Xsamples)

        scores = self.acquisition(X_red, Xsamples_red, model)

        # Highest-EI candidate that has not been evaluated yet
        for ix in np.argsort(scores)[::-1]:
            candidate = Xsamples[ix]
            if not any(np.array_equal(candidate, x_prev) for x_prev in X):
                return candidate

        return None

    def optimize(self, initial_X, initial_y, iterations=50):
        X = np.array(initial_X)
        y = np.array(initial_y)

        # Fit the surrogate in the reduced space
        X_red = self._reduce_X(X)
        self.model.fit(X_red, y)

        history_y = []
        best_current_y = np.max(y)

        for i in range(iterations):
            x_next = self.opt_acquisition(X, y, self.model)
            if x_next is None: break

            actual = self.objective_func(self.problem, x_next)

            X = np.concatenate((X, [x_next]))
            y = np.concatenate((y, [actual]))

            # Refit the surrogate
            X_red = self._reduce_X(X)
            self.model.fit(X_red, y)

            if actual > best_current_y:
                best_current_y = actual
            history_y.append(best_current_y)
            print(f"> BO Iter {i+1}: observed = {actual:.3f}, best so far = {best_current_y:.3f}")

        ix = np.argmax(y)
        return X[ix], y[ix], history_y
